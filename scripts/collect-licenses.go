// Run from the repository root after go mod download:
// go run scripts/collect-licenses.go
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir string
	Main               bool
	Replace            *module
}

func main() {
	if err := collect(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func collect() error {
	manifest, err := exec.Command("go", "mod", "edit", "-json").Output()
	if err != nil {
		return err
	}
	var requirements struct {
		Require []struct{ Path string }
	}
	if err := json.Unmarshal(manifest, &requirements); err != nil {
		return err
	}
	if len(requirements.Require) == 0 {
		return fmt.Errorf("no dependency modules in go.mod")
	}
	args := []string{"list", "-mod=readonly", "-m", "-json"}
	for _, requirement := range requirements.Require {
		args = append(args, requirement.Path)
	}
	cmd := exec.Command("go", args...)
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return err
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	var modules []module
	for {
		var m module
		if err := decoder.Decode(&m); err == io.EOF {
			break
		} else if err != nil {
			return err
		}
		if !m.Main {
			modules = append(modules, m)
		}
	}
	sort.Slice(modules, func(i, j int) bool { return modules[i].Path < modules[j].Path })
	var out bytes.Buffer
	out.WriteString("THIRD-PARTY NOTICES\n\nGenerated by go run scripts/collect-licenses.go.\n")
	out.WriteString("Direct and indirect modules pinned in go.mod are included below.\n")
	out.WriteString("These are upstream notices; each component retains its own license.\n")
	out.WriteString("The full GNU GPL v3 text is supplied separately in LICENSE.\n")
	for _, m := range modules {
		if m.Replace != nil {
			return fmt.Errorf("review replacement licensing before collecting notices for %s", m.Path)
		}
		if m.Dir == "" {
			return fmt.Errorf("%s is not downloaded; run go mod download first", m.Path)
		}
		entries, err := os.ReadDir(m.Dir)
		if err != nil {
			return err
		}
		var files []string
		for _, entry := range entries {
			if entry.IsDir() {
				continue
			}
			name := strings.ToUpper(entry.Name())
			for _, prefix := range []string{"LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE"} {
				if name == prefix || strings.HasPrefix(name, prefix+".") || strings.HasPrefix(name, prefix+"-") || strings.HasPrefix(name, prefix+"_") {
					files = append(files, entry.Name())
					break
				}
			}
		}
		if len(files) == 0 {
			return fmt.Errorf("no root licensing files found for %s@%s; review upstream licensing", m.Path, m.Version)
		}
		sort.Strings(files)
		fmt.Fprintf(&out, "\n%s\nModule: %s@%s\n", strings.Repeat("=", 78), m.Path, m.Version)
		fmt.Fprintf(&out, "Source archive: https://proxy.golang.org/%s/@v/%s.zip\n", escapeModule(m.Path), escapeModule(m.Version))
		for _, name := range files {
			text, err := os.ReadFile(filepath.Join(m.Dir, name))
			if err != nil {
				return err
			}
			fmt.Fprintf(&out, "\n--- %s ---\n%s\n", name, bytes.TrimRight(text, "\r\n"))
		}
	}
	if err := os.WriteFile("THIRD_PARTY_NOTICES.txt", out.Bytes(), 0644); err != nil {
		return err
	}
	fmt.Printf("Collected notices for %d dependency modules\n", len(modules))
	return nil
}

// Module proxy paths encode uppercase letters as ! followed by lowercase.
func escapeModule(value string) string {
	var escaped strings.Builder
	for _, ch := range value {
		if ch >= 'A' && ch <= 'Z' {
			escaped.WriteByte('!')
			ch += 'a' - 'A'
		}
		escaped.WriteRune(ch)
	}
	return escaped.String()
}
